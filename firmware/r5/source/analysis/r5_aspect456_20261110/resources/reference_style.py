def require(condition, message):
    if not condition:
        raise ValueError(message)


def string_records(raw):
    require(len(raw) >= 16 and raw[:4] == b'uxc\x07', '不是字符串 UXC')
    count, remainder = divmod(struct.unpack_from('<I', raw, 12)[0], 0x1001)
    require(not remainder and 0 < count <= 8192, '字符串索引计数异常')
    base = (16 + 2 * count + 3) & ~3
    require(base <= len(raw), '字符串索引截断')
    first = 0x1e000000 + (struct.unpack_from('<H', raw, 10)[0] << 13)
    records = {}
    for index in range(count):
        word = struct.unpack_from('<H', raw, 16 + 2 * index)[0]
        if word == 0xffff:
            continue
        at = base + word * 4
        require(base <= at and at + 4 < len(raw), '字符串记录越界')
        key = struct.unpack_from('<I', raw, at)[0]
        require(key == first + index, '字符串 ID 与索引不符')
        end = raw.find(b'\0', at + 4)
        require(end >= 0, '字符串缺少终止符')
        records[key - 0x1c000000] = raw[at + 4:end].decode('utf-8')
    return count, base, first, records


def add_labels(raw):
    count, base, first, records = string_records(raw)
    for key in TEXT_IDS:
        require(key not in records and 0 <= key + 0x1c000000 - first < count,
                f'比例文字 ID 不可用：{key:#x}')
    expected = records | dict(zip(TEXT_IDS, LABELS))
    # 活跃记录重排可回收废弃追加项，最长字符串末置以保留 u16 起始地址空间。
    output = bytearray(raw[:base])
    output[16:16 + 2 * count] = b'\xff\xff' * count
    for key, text in sorted(expected.items(), key=lambda item: (len(item[1].encode('utf-8')), item[0])):
        index = key + 0x1c000000 - first
        word = (len(output) - base) // 4
        require(word < 0xffff, '字符串记录超过 u16 字偏移范围')
        struct.pack_into('<H', output, 16 + 2 * index, word)
        output.extend(struct.pack('<I', key + 0x1c000000) + text.encode('utf-8') + b'\0')
        output.extend(bytes(-len(output) % 4))
    result = bytes(output)
    require(string_records(result)[3] == expected, '字符串回读不符')
    return result


def decompress_block(raw, start=0):
    require(start < len(raw) and raw[start] == 0xf0, '压缩块缺少 F0')
    output = bytearray()
    cursor = start + 1
    while cursor < len(raw):
        flags = raw[cursor]
        cursor += 1
        for bit in range(8):
            require(cursor < len(raw), '压缩 token 截断')
            if flags & (1 << bit):
                require(cursor + 2 <= len(raw), '压缩引用截断')
                a, b = raw[cursor:cursor + 2]
                cursor += 2
                distance = ((a & 15) << 8) | b
                if distance == 0:
                    require(len(output) <= 4096, '解压块超过 4 KiB')
                    return bytes(output), cursor
                length = LENGTHS[a >> 4]
                require(distance <= len(output) and len(output) + length <= 4096,
                        '压缩引用越界或跨越输出块')
                for _ in range(length):
                    output.append(output[-distance])
            else:
                require(len(output) < 4096, '解压块超过 4 KiB')
                output.append(raw[cursor])
                cursor += 1
    raise ValueError('压缩块没有结束引用')


def compress_block(raw):
    require(0 < len(raw) <= 4096, '每块须为 1..4096 字节')
    positions = defaultdict(deque)
    tokens = []
    cursor = 0
    while cursor < len(raw):
        maximum = min(64, len(raw) - cursor)
        length = distance = 0
        if maximum >= 3:
            key = raw[cursor:cursor + 3]
            candidates = positions[key]
            while candidates and cursor - candidates[0] > 4095:
                candidates.popleft()
            for before in reversed(candidates):
                size = 3
                while size < maximum and raw[before + size] == raw[cursor + size]:
                    size += 1
                permitted = next((n for n in reversed(LENGTHS) if n <= size), 0)
                if permitted > length:
                    length, distance = permitted, cursor - before
                    if length == 64:
                        break
        consumed = length or 1
        if length:
            code = LENGTHS.index(length)
            tokens.append((True, bytes([(code << 4) | (distance >> 8), distance & 255])))
        else:
            tokens.append((False, raw[cursor:cursor + 1]))
        for at in range(cursor, cursor + consumed):
            if at + 3 <= len(raw):
                positions[raw[at:at + 3]].append(at)
        cursor += consumed
    tokens.append((True, b'\0\0'))
    output = bytearray(b'\xf0')
    for at in range(0, len(tokens), 8):
        group = tokens[at:at + 8]
        output.append(sum(1 << i for i, (reference, _) in enumerate(group) if reference))
        output.extend(b''.join(data for _, data in group))
    require(len(output) <= 4096, '图标压缩输入块超过原解码器的 4 KiB 限制')
    decoded, end = decompress_block(output)
    require(decoded == raw and end == len(output), '图标压缩回读失败')
    return bytes(output)


