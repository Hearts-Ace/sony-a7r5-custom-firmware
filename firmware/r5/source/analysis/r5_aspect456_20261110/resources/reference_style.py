def image_records(raw):
    require(len(raw) >= 16 and raw[:4] == b'uxd\x07', '不是图像 UXC')
    count = struct.unpack_from('<I', raw, 12)[0] & 0x1fff
    require(0 < count <= 8191, '图像索引计数异常')
    base = (16 + 2 * count + 3) & ~3
    require(base <= len(raw), '图像索引截断')
    first = 0x1a000000 + (struct.unpack_from('<H', raw, 10)[0] << 13)
    rows = {}
    for index in range(count):
        word = struct.unpack_from('<H', raw, 16 + index * 2)[0]
        if word == 0xffff:
            continue
        at = base + word * 4
        require(at + 20 <= len(raw), '图像 descriptor 截断')
        key, flags = struct.unpack_from('<II', raw, at)
        require(key == first + index and flags in (0xc0000000, 0x40000000, 0xc8000000, 0x48000000),
                '图像 ID／descriptor 类型异常')
        size = 40 if flags & 0x08000000 else 20
        require(at + size <= len(raw), '九宫格 descriptor 截断')
        offset = size - 4
        length = struct.unpack_from('<I', raw, at + offset - 4)[0]
        payload = at + 4 + struct.unpack_from('<I', raw, at + offset)[0]
        require(length > 0 and at + size <= payload and payload + length <= len(raw),
                '图像 payload 越界')
        require(index not in rows, '重复图像 ID')
        rows[index] = dict(at=at, size=size, payload=payload, length=length,
                           header=raw[at:at + size], data=raw[payload:payload + length])
    require(rows, '空图像银行')
    starts = sorted((row['at'], row['at'] + row['size']) for row in rows.values())
    require(all(end <= start for (_, end), (start, _) in zip(starts, starts[1:])), '图像 descriptor 重叠')
    require(max(end for _, end in starts) <= min(row['payload'] for row in rows.values()),
            '图像 descriptor 与 payload 区域交错')
    return count, base, first, rows


def add_icons(raw, variant='23'):
    count, base, first, rows = image_records(raw)
    require(first == 0x1a000000, '比例图标仅放入 bank 0')
    entries = [(key-0x02000000, 70, 60, icon_stream(LABELS[i%4], i>=4, variant),
                icon_pixels(LABELS[i%4], i>=4, variant)) for i, key in enumerate(IMAGE_IDS)]
    entries.extend((key-0x02000000, 47, 32, playback_stream(label, variant),
                    playback_pixels(label, variant)) for key, label in zip(PLAYBACK_IDS, PLAYBACK_LABELS))
    entries.append((MEGAPIXEL_47_ID-0x02000000, 48, 32, megapixel_47_stream(variant),
                    megapixel_47_pixels(variant)))
    entries.extend((key-0x02000000, 47, 32, current_playback_stream(label, variant),
                    current_playback_pixels(label, variant))
                   for key, label in zip(CURRENT_PLAYBACK_IDS, CURRENT_PLAYBACK_LABELS))
    entries.extend((key-0x02000000, 48, 32, megapixel_stream(label, variant),
                    megapixel_pixels(label, variant))
                   for key, label in zip(MEGAPIXEL_IDS, MEGAPIXEL_LABELS))
    indices = tuple(entry[0] for entry in entries)
    require(all(index < count and index not in rows for index in indices), '比例图标 ID 已占用或超出索引')
    at = max(row['at'] + row['size'] for row in rows.values())
    extra = len(entries) * 20
    output = bytearray(raw[:at] + bytes(extra) + raw[at:])
    for row in rows.values():
        field = row['at'] + row['size'] - 4
        old = struct.unpack_from('<I', raw, field)[0]
        struct.pack_into('<I', output, field, old + extra)
    for i, (index, width, height, stream, _) in enumerate(entries):
        position = at + i * 20
        word = (position - base) // 4
        require(word < 0xffff, '新增图像 descriptor 超过 u16 字偏移范围')
        payload = len(output)
        struct.pack_into('<IIHHII', output, position, first + index, 0xc0000000, width, height,
                         len(stream), payload - position - 4)
        struct.pack_into('<H', output, 16 + index * 2, word)
        output.extend(stream)
        output.extend(bytes(-len(output) % 4))
    result = bytes(output)
    new_rows = image_records(result)[3]
    require(set(new_rows) == set(rows) | set(indices), '图像索引回读不符')
    for index, old in rows.items():
        new = new_rows[index]
        require(old['header'][:-4] == new['header'][:-4] and old['data'] == new['data'],
                f'原有图像内容改变：{index:#x}')
    for index, _, _, _, expected in entries:
        compressed = new_rows[index]['data']
        cursor = 0
        decoded = bytearray()
        for at in range(0, len(expected), 4096):
            size = min(4096, len(expected)-at)
            block, end = decompress_block(compressed, cursor)
            require(len(block) == size and end-cursor <= 4096, '图标解压块长度异常')
            decoded.extend(block)
            cursor = end
        require(cursor == len(compressed) and decoded == expected, '图标完整流回读失败')
    return result
